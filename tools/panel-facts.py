#!/usr/bin/env python3
"""Identify this phone's panel out of its own device tree.

The SDE device tree describes many panels; the one that is actually fitted is the node the
`qcom,dsi-display-primary` node points at through `qcom,dsi-default-panel`. Following that phandle
gives the panel's name, its DSC mode and its timings -- in particular the refresh rate, which the
framebuffer and the window server need and which the phone's boot arguments must carry.

The common repository's metal.args is a line of boot-arguments and was shipped with fb_hz=60 here;
this phone's only panel timing is 120 Hz. The generated file is the evidence, and CI checks it.

Usage:
  python3 tools/panel-facts.py --dtb uefi/files/Resources/DTBs/cupid.dtb --out docs/panel-facts.txt
  python3 tools/panel-facts.py --dtb uefi/files/Resources/DTBs/cupid.dtb --check docs/panel-facts.txt
"""

import argparse
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def _facts():
    spec = importlib.util.spec_from_file_location("gpu_facts", os.path.join(HERE, "gpu-facts.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


FACTS = _facts()


def cells(raw):
    try:
        return FACTS.cells(raw)
    except Exception:
        return []


def text(raw):
    return raw.replace(b"\\x00", b"\0").split(b"\0")[0].decode("utf-8", "replace")


def build(nodes):
    primary = nodes.get("/soc/qcom,dsi-display-primary")
    if not primary or "qcom,dsi-default-panel" not in primary:
        return None
    by_phandle = {}
    for path, props in nodes.items():
        if "phandle" in props:
            values = cells(props["phandle"])
            if values:
                by_phandle[values[0]] = path
    handle = cells(primary["qcom,dsi-default-panel"])
    if not handle or handle[0] not in by_phandle:
        return None
    panel = by_phandle[handle[0]]
    props = nodes[panel]

    def value(name):
        return cells(props[name])[0] if name in props and cells(props[name]) else None

    out = {
        "panel_node": panel,
        "phandle": handle[0],
        "panel_name": text(props["qcom,mdss-dsi-panel-name"]) if "qcom,mdss-dsi-panel-name" in props else None,
        "bpp": value("qcom,mdss-dsi-bpp"),
        "dfs_list": value("qcom,dsi-supported-dfps-list"),
        "min_refresh": value("qcom,mdss-dsi-min-refresh-rate"),
        "max_refresh": value("qcom,mdss-dsi-max-refresh-rate"),
        "timings": [],
    }
    base = panel + "/qcom,mdss-dsi-display-timings/"
    for path, child in sorted(nodes.items()):
        if not path.startswith(base) or path == base:
            continue

        def child_value(name):
            return cells(child[name])[0] if name in child and cells(child[name]) else None

        out["timings"].append({
            "name": path[len(base):],
            "hz": child_value("qcom,mdss-dsi-panel-framerate"),
            "width": child_value("qcom,mdss-dsi-panel-width"),
            "height": child_value("qcom,mdss-dsi-panel-height"),
        })
    return out


def render(info):
    lines = [
        "# The panel of the Xiaomi 12 (cupid), read out of the phone's own device tree.",
        "# Generated by tools/panel-facts.py. Do not edit by hand; CI re-checks it.",
        "#",
        "# The tree describes many panels. The one fitted is the node the primary display's",
        "# qcom,dsi-default-panel phandle points at.",
        "#",
    ]
    for key in ("panel_node", "phandle", "panel_name", "bpp", "dfs_list", "min_refresh", "max_refresh"):
        value = info[key]
        lines.append("%-20s %s" % (key, value if value is not None else "(not in the tree)"))
    for timing in info["timings"]:
        lines.append("%-20s %s  hz=%s  %sx%s"
                     % ("timing", timing["name"], timing["hz"], timing["width"], timing["height"]))
    if info["timings"]:
        hz = sorted({t["hz"] for t in info["timings"] if t["hz"]})
        lines.append("%-20s %s" % ("refresh_rates", ", ".join(str(h) for h in hz)))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dtb", default="uefi/files/Resources/DTBs/cupid.dtb")
    parser.add_argument("--out", default="docs/panel-facts.txt")
    parser.add_argument("--check")
    args = parser.parse_args()

    nodes = FACTS.fdt_nodes(open(args.dtb, "rb").read())
    info = build(nodes)
    if info is None:
        print("panel-facts: the tree has no primary display panel to identify")
        return 1
    text_out = render(info)
    if args.check:
        current = open(args.check, encoding="utf-8").read()
        if current != text_out:
            print("panel-facts: %s does not match %s; regenerate it with --out" % (args.check, args.dtb))
            return 1
        print("panel-facts: %s matches %s" % (args.check, os.path.basename(args.dtb)))
        return 0
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text_out)
    print("panel-facts: wrote %s (%s, %d timing(s))"
          % (args.out, info["panel_name"], len(info["timings"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
